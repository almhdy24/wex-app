#!/usr/bin/env python3
"""Generate lib/core/design/colors.g.dart (and optionally a tokens.css) from tokens/tokens.json.

Usage: python3 scripts/gen_tokens.py [--css path/to/tokens.css]
No hex literal may exist outside generated files (tools/verify_ui.sh enforces it).
"""
import json, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
tok = json.loads((root / "tokens/tokens.json").read_text())
c = tok["color"]

def dart_color(h):
    return "Color(0xFF%s)" % h.lstrip("#").upper()

# Legacy names (pre-v2 code) -> new token, so old call sites keep compiling while screens migrate.
LEGACY = {
    "primary": "teal600", "primaryDeep": "teal700", "violet": "teal500", "royal": "teal600",
    "vivid": "teal600", "cyan": "teal600", "navy": "ink900", "textPrimary": "ink900",
    "textSecondary": "muted", "border": "line", "ice": "paper", "iceLight": "sunken",
    "white": "surface", "onDark": "surface", "warning": "sun700", "warningBg": "sun50",
    "neutral": "muted", "neutralBg": "sunken", "primaryTint": "teal50",
}

out = ["// GENERATED by scripts/gen_tokens.py from tokens/tokens.json. Do not edit.",
       "import 'package:flutter/painting.dart';", "",
       "abstract final class WexColors {"]
for k, v in c.items():
    out.append(f"  static const {k} = {dart_color(v)};")
out.append("")
out.append("  // Legacy aliases (pre-v2 names).")
for k, v in LEGACY.items():
    out.append(f"  static const {k} = {v};")
out.append("  static const onDarkMuted = onInkMuted;")
a = tok["shadow"]["floatAlpha"]
out.append(f"  static const shadowSoft = Color.fromRGBO(11, 31, 42, {a});")
out.append(f"  static const shadowSticky = Color.fromRGBO(11, 31, 42, {a});")
g = tok["gradient"]
out.append("")
out.append("  /// The ONLY gradient in the product.")
out.append(f"  static const heroFrom = {dart_color(g['heroFrom'])};")
out.append(f"  static const heroTo = {dart_color(g['heroTo'])};")
out.append("}")
(root / "lib/core/design/colors.g.dart").write_text("\n".join(out) + "\n")

# Optional CSS output for the web/admin.
if "--css" in sys.argv:
    path = pathlib.Path(sys.argv[sys.argv.index("--css") + 1])
    css = [":root {"]
    for k, v in c.items():
        name = "".join("-" + ch.lower() if ch.isupper() else ch for ch in k)
        css.append(f"  --v2-{name}: {v};")
    for i, sp in enumerate(tok["space"]):
        css.append(f"  --v2-space-{i + 1}: {sp}px;")
    for k, v in tok["radius"].items():
        css.append(f"  --v2-radius-{''.join('-' + c.lower() if c.isupper() else c for c in k)}: {v}px;")
    for k, v in tok["motion"].items():
        css.append(f"  --v2-motion-{k}: {v}ms;")
    css.append(f"  --hero-gradient: linear-gradient({g['angle']}deg, {g['heroFrom']}, {g['heroTo']});")
    css.append(f"  --shadow-float: 0 -1px 0 {c['line']}, 0 -8px 24px rgba(11, 31, 42, {a});")
    css.append("}")
    path.write_text("\n".join(css) + "\n")
print("generated")
